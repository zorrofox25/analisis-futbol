"""Persistencia PostgreSQL (Supabase) para el historial de predicciones."""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
from typing import Any

import pandas as pd
import numpy as np
import psycopg
import streamlit as st
from psycopg.rows import dict_row


@dataclass(frozen=True)
class PrediccionGuardada:
    """Campos que se guardan para dejar constancia de una predicción."""

    codigo_liga: str
    nombre_liga: str
    equipo_local: str
    equipo_visitante: str
    cuota_1: float
    cuota_x: float
    cuota_2: float
    probabilidad_1: float
    probabilidad_x: float
    probabilidad_2: float
    ev_1: float
    ev_x: float
    ev_2: float
    ev_1_porcentaje: float
    ev_x_porcentaje: float
    ev_2_porcentaje: float
    lambda_local: float
    lambda_visitante: float
    pronostico_1x2: str
    mercado_recomendado: str | None
    cuota_recomendada: float | None
    metricas_avanzadas: dict[str, Any] | None = None


def _json_default(valor: Any) -> Any:
    """Convierte tipos NumPy/Pandas usados por el modelo a JSON estándar."""
    if isinstance(valor, pd.DataFrame):
        return {
            "index": valor.index.tolist(),
            "columns": valor.columns.tolist(),
            "values": valor.to_numpy().tolist(),
        }
    if isinstance(valor, (np.integer, np.floating, np.bool_)):
        return valor.item()
    if isinstance(valor, (pd.Timestamp, datetime)):
        return valor.isoformat()
    raise TypeError(f"Tipo no serializable a JSON: {type(valor).__name__}")


CREATE_TABLE_SQL = """
CREATE TABLE IF NOT EXISTS predicciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_utc TIMESTAMPTZ NOT NULL,
    codigo_liga TEXT NOT NULL,
    nombre_liga TEXT NOT NULL,
    equipo_local TEXT NOT NULL,
    equipo_visitante TEXT NOT NULL,
    cuota_1 DOUBLE PRECISION NOT NULL,
    cuota_x DOUBLE PRECISION NOT NULL,
    cuota_2 DOUBLE PRECISION NOT NULL,
    probabilidad_1 DOUBLE PRECISION NOT NULL,
    probabilidad_x DOUBLE PRECISION NOT NULL,
    probabilidad_2 DOUBLE PRECISION NOT NULL,
    ev_1 DOUBLE PRECISION NOT NULL,
    ev_x DOUBLE PRECISION NOT NULL,
    ev_2 DOUBLE PRECISION NOT NULL,
    ev_1_porcentaje DOUBLE PRECISION NOT NULL,
    ev_x_porcentaje DOUBLE PRECISION NOT NULL,
    ev_2_porcentaje DOUBLE PRECISION NOT NULL,
    lambda_local DOUBLE PRECISION NOT NULL,
    lambda_visitante DOUBLE PRECISION NOT NULL,
    pronostico_1x2 TEXT,
    mercado_recomendado TEXT,
    cuota_recomendada DOUBLE PRECISION,
    estado_resultado TEXT NOT NULL DEFAULT 'PENDIENTE',
    resultado_real TEXT,
    acierto SMALLINT,
    roi_unidades DOUBLE PRECISION,
    fecha_resultado_utc TIMESTAMPTZ,
    datos JSONB NOT NULL
)
"""


def _conectar() -> psycopg.Connection[Any]:
    """Abre una conexión TLS usando DATABASE_URL de Streamlit Secrets."""
    try:
        database_url = str(st.secrets["DATABASE_URL"])
    except (KeyError, FileNotFoundError) as exc:
        raise RuntimeError("Falta configurar DATABASE_URL en Streamlit Secrets.") from exc
    return psycopg.connect(
        database_url,
        sslmode="require",
        connect_timeout=10,
        row_factory=dict_row,
    )


def inicializar_historial() -> None:
    """Crea la tabla e índice de PostgreSQL si todavía no existen."""
    with _conectar() as conexion:
        conexion.execute(CREATE_TABLE_SQL)
        conexion.execute(
            "CREATE INDEX IF NOT EXISTS idx_predicciones_fecha "
            "ON predicciones (fecha_utc DESC)"
        )


def guardar_prediccion(prediccion: PrediccionGuardada) -> int:
    """Guarda los campos consultables y el objeto completo en JSONB."""
    inicializar_historial()
    datos = asdict(prediccion)
    fecha_utc = datetime.now(timezone.utc)
    columnas = (
        "fecha_utc, codigo_liga, nombre_liga, equipo_local, equipo_visitante, "
        "cuota_1, cuota_x, cuota_2, probabilidad_1, probabilidad_x, probabilidad_2, "
        "ev_1, ev_x, ev_2, ev_1_porcentaje, ev_x_porcentaje, ev_2_porcentaje, "
        "lambda_local, lambda_visitante, pronostico_1x2, mercado_recomendado, "
        "cuota_recomendada, datos"
    )
    valores = (
        fecha_utc,
        prediccion.codigo_liga,
        prediccion.nombre_liga,
        prediccion.equipo_local,
        prediccion.equipo_visitante,
        prediccion.cuota_1,
        prediccion.cuota_x,
        prediccion.cuota_2,
        prediccion.probabilidad_1,
        prediccion.probabilidad_x,
        prediccion.probabilidad_2,
        prediccion.ev_1,
        prediccion.ev_x,
        prediccion.ev_2,
        prediccion.ev_1_porcentaje,
        prediccion.ev_x_porcentaje,
        prediccion.ev_2_porcentaje,
        prediccion.lambda_local,
        prediccion.lambda_visitante,
        prediccion.pronostico_1x2,
        prediccion.mercado_recomendado,
        prediccion.cuota_recomendada,
        json.dumps(datos, ensure_ascii=False, default=_json_default),
    )
    with _conectar() as conexion:
        fila = conexion.execute(
            f"INSERT INTO predicciones ({columnas}) VALUES ("
            + ", ".join(["%s"] * 22)
            + ", %s::jsonb) RETURNING id",
            valores,
        ).fetchone()
    return int(fila["id"])


def leer_historial(limite: int = 500) -> pd.DataFrame:
    """Lee las predicciones más recientes como DataFrame compatible con la app."""
    if limite < 1:
        raise ValueError("El límite del historial debe ser mayor que cero.")
    inicializar_historial()
    with _conectar() as conexion:
        filas = conexion.execute(
            "SELECT * FROM predicciones ORDER BY fecha_utc DESC, id DESC LIMIT %s",
            (limite,),
        ).fetchall()
    return pd.DataFrame(filas)


def liquidar_predicciones(partidos: pd.DataFrame, codigo_liga: str) -> int:
    """Liquida predicciones pendientes al aparecer un resultado posterior coincidente."""
    requeridas = {"HomeTeam", "AwayTeam", "FTHG", "FTAG", "MatchDate"}
    if not requeridas.issubset(partidos.columns):
        return 0
    resultados = partidos.copy()
    resultados["MatchDate"] = pd.to_datetime(resultados["MatchDate"], utc=True, errors="coerce")
    resultados = resultados.dropna(subset=["MatchDate", "FTHG", "FTAG"])
    if resultados.empty:
        return 0

    inicializar_historial()
    liquidadas = 0
    with _conectar() as conexion:
        pendientes = conexion.execute(
            """SELECT id, fecha_utc, equipo_local, equipo_visitante,
                      probabilidad_1, probabilidad_x, probabilidad_2,
                      pronostico_1x2, mercado_recomendado, cuota_recomendada
               FROM predicciones
               WHERE codigo_liga = %s AND estado_resultado = 'PENDIENTE'""",
            (codigo_liga,),
        ).fetchall()

        for fila in pendientes:
            candidatos = resultados[
                (resultados["HomeTeam"] == fila["equipo_local"])
                & (resultados["AwayTeam"] == fila["equipo_visitante"])
                & (resultados["MatchDate"] > pd.Timestamp(fila["fecha_utc"]))
            ].sort_values("MatchDate")
            if candidatos.empty:
                continue

            partido = candidatos.iloc[0]
            goles_local, goles_visitante = int(partido["FTHG"]), int(partido["FTAG"])
            resultado_real = "1" if goles_local > goles_visitante else "2" if goles_local < goles_visitante else "X"
            pronostico = fila["pronostico_1x2"]
            if pronostico not in {"1", "X", "2"}:
                pronostico = max(
                    (("1", fila["probabilidad_1"]), ("X", fila["probabilidad_x"]), ("2", fila["probabilidad_2"])),
                    key=lambda par: par[1],
                )[0]
            acierto = int(pronostico == resultado_real)

            recomendado = fila["mercado_recomendado"]
            ambos_marcan = goles_local > 0 and goles_visitante > 0
            ganadoras = {
                "1": resultado_real == "1", "X": resultado_real == "X", "2": resultado_real == "2",
                "1X": resultado_real in {"1", "X"}, "12": resultado_real in {"1", "2"},
                "X2": resultado_real in {"X", "2"}, "O2.5": goles_local + goles_visitante >= 3,
                "U2.5": goles_local + goles_visitante <= 2, "BTTS_SI": ambos_marcan,
                "BTTS_NO": not ambos_marcan,
            }
            cuota = fila["cuota_recomendada"]
            roi = (float(cuota) - 1.0 if ganadoras[recomendado] else -1.0) if recomendado in ganadoras and cuota is not None else None
            conexion.execute(
                """UPDATE predicciones
                   SET estado_resultado = 'LIQUIDADA', resultado_real = %s, acierto = %s,
                       roi_unidades = %s, fecha_resultado_utc = %s
                   WHERE id = %s""",
                (resultado_real, acierto, roi, partido["MatchDate"].to_pydatetime(), fila["id"]),
            )
            liquidadas += 1
    return liquidadas


def resumen_rendimiento() -> dict[str, float | int | None]:
    """Calcula acierto 1X2 y ROI real de apuestas recomendadas ya liquidadas."""
    inicializar_historial()
    with _conectar() as conexion:
        fila = conexion.execute(
            """SELECT COUNT(*) AS total,
                      COUNT(*) FILTER (WHERE estado_resultado = 'LIQUIDADA') AS liquidadas,
                      COALESCE(SUM(acierto) FILTER (WHERE estado_resultado = 'LIQUIDADA'), 0) AS correctas,
                      COUNT(*) FILTER (WHERE estado_resultado = 'LIQUIDADA'
                                       AND mercado_recomendado IS NOT NULL AND roi_unidades IS NOT NULL) AS apuestas,
                      COUNT(*) FILTER (WHERE estado_resultado = 'LIQUIDADA' AND roi_unidades > 0) AS ganadas,
                      COALESCE(SUM(roi_unidades) FILTER (WHERE estado_resultado = 'LIQUIDADA'
                                       AND mercado_recomendado IS NOT NULL AND roi_unidades IS NOT NULL), 0) AS roi_total
               FROM predicciones"""
        ).fetchone()
    total, liquidadas = int(fila["total"]), int(fila["liquidadas"])
    correctas, apuestas = int(fila["correctas"]), int(fila["apuestas"])
    return {
        "predicciones_guardadas": total,
        "partidos_liquidados": liquidadas,
        "aciertos_pronostico": correctas,
        "porcentaje_acierto": correctas / liquidadas * 100 if liquidadas else None,
        "apuestas_liquidadas": apuestas,
        "apuestas_ganadas": int(fila["ganadas"]),
        "roi_porcentaje": float(fila["roi_total"]) / apuestas * 100 if apuestas else None,
    }
